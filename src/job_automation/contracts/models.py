"""C10 ModelCall and ModelResult contracts.

Represents structured invocation of local model inference and standardized execution results.
Never includes credentials or arbitrary tool authority in prompts or settings.
"""

from __future__ import annotations

import uuid
from typing import Any, Self

from pydantic import Field, model_validator

from job_automation.contracts.base import ContractModel
from job_automation.contracts.errors import ClassifiedError


class TokenUsage(ContractModel):
    """Token usage metrics. Null values represent unknown or unmeasured metrics."""

    prompt_tokens: int | None = Field(default=None, ge=0)
    completion_tokens: int | None = Field(default=None, ge=0)
    total_tokens: int | None = Field(default=None, ge=0)


class ModelCall(ContractModel):
    """C10 Model Call specification.

    Frozen invocation parameters for reproducible local model execution.
    """

    call_id: uuid.UUID = Field(description="Unique UUID for this inference call")
    operation_type: str = Field(
        min_length=1,
        description="Type of operation (e.g. 'relevance_assessment', 'draft_cv')",
    )
    model_identifier: str = Field(
        min_length=1,
        description="Local model name/tag (e.g. 'llama3:8b-instruct-q4_K_M')",
    )
    model_digest: str | None = Field(
        default=None,
        description="Optional digest/hash of the local model weights",
    )
    prompt_version: str = Field(
        min_length=1,
        description="Version identifier of the prompt template used",
    )
    system_prompt_version: str | None = Field(
        default=None,
        description="Version identifier of system prompt if separated",
    )
    generation_settings: dict[str, Any] = Field(
        default_factory=dict,
        description="Model parameters (e.g. {'temperature': 0.1, 'top_p': 0.9})",
    )
    context_limit: int = Field(gt=0, description="Maximum context window size for the model")
    input_fingerprint: str = Field(
        min_length=1,
        description="Content hash/fingerprint of the combined prompt input",
    )
    requested_schema: str | None = Field(
        default=None,
        description="Name or ID of JSON schema for structured output generation",
    )


class ModelResult(ContractModel):
    """C10 Model Result.

    Standardized output from local model execution with timing and error classification.
    """

    call_id: uuid.UUID = Field(description="UUID linking to the corresponding ModelCall")
    model_identifier: str = Field(min_length=1, description="Model that executed the call")
    model_digest: str | None = Field(default=None, description="Digest of model weights")
    output_text: str | None = Field(
        default=None, description="Raw text generated by the model; null on error"
    )
    parsed_output: dict[str, Any] | None = Field(
        default=None, description="Parsed structured JSON output if applicable"
    )
    error: ClassifiedError | None = Field(
        default=None, description="Classified error if execution failed"
    )
    latency_ms: float = Field(ge=0.0, description="Execution duration in milliseconds")
    token_usage: TokenUsage | None = Field(
        default=None,
        description="Token usage statistics if provided by the model service",
    )

    @model_validator(mode="after")
    def _validate_exclusive_result(self) -> Self:
        if self.error is not None:
            if self.output_text is not None or self.parsed_output is not None:
                raise ValueError("ModelResult with error must have null output_text and parsed_output")
        return self

