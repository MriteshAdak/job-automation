class ArtifactReviewService:
    """Production-grade service managing artifact review, file permissions, and approval invariants."""

    def __init__(
        self,
        submission_service: GenerationSubmissionService | None = None,
        org_id: str = "00D000000000001AAA",
    ) -> None:
        self.org_id = org_id
        self.submission_service = submission_service or GenerationSubmissionService()
        self._lock = threading.RLock()

        # Database tables
        self._review_records: dict[str, ArtifactReviewRecord] = {}  # review_id -> record
        self._events: dict[str, ArtifactReviewEventRecord] = {}  # event_id -> event
        self._event_keys: dict[str, tuple[str, str]] = {}  # event_key -> (event_id, canonical_payload)
        self._binding_keys: dict[str, str] = {}  # binding_key -> review_id

        # Simulated Salesforce Files & Links
        # content_version_id -> {"document_id": str, "title": str, "version_data": bytes, "is_deleted": bool}
        self._files: dict[str, dict[str, Any]] = {}
        # content_document_id -> list of links: {"target_id": str, "share_type": str, "visibility": str}
        self._links: dict[str, list[dict[str, str]]] = {}

        # User permissions: user_id -> set of permissions
        self._user_permissions: dict[str, set[str]] = {}
        self._user_roles: dict[str, str] = {}  # user_id -> "candidate" | "worker" | "unrelated"

        # AutoNumber sequences
        self._review_seq = 1
        self._event_seq = 1

    # --- Setup & Configuration Helpers ---

    def register_user(
        self,
        user_id: str,
        role: str = "candidate",
        custom_permissions: set[str] | None = None,
    ) -> None:
        """Register user role and custom permissions."""
        with self._lock:
            self._user_roles[user_id] = role
            perms = set(custom_permissions or set())
            if role == "candidate":
                perms.add("JA_Review_Generated_Documents")
            self._user_permissions[user_id] = perms

    def register_content_version(
        self,
        content_version_id: str,
        content_document_id: str,
        title: str = "Document",
        is_deleted: bool = False,
    ) -> None:
        """Register a remote ContentVersion."""
        with self._lock:
            self._files[content_version_id] = {
                "document_id": content_document_id,
                "title": title,
                "is_deleted": is_deleted,
            }

    def register_content_document_link(
        self,
        content_document_id: str,
        target_id: str,
        share_type: str = "V",
        visibility: str = "AllUsers",
    ) -> None:
        """Register a ContentDocumentLink."""
        with self._lock:
            if content_document_id not in self._links:
                self._links[content_document_id] = []
            self._links[content_document_id].append(
                {
                    "target_id": canonicalize_salesforce_id(target_id),
                    "share_type": share_type,
                    "visibility": visibility,
                }
            )

    def revoke_content_document_link(self, content_document_id: str, target_id: str) -> None:
        """Remove a link to simulate access revocation."""
        with self._lock:
            canon_target = canonicalize_salesforce_id(target_id)
            if content_document_id in self._links:
                self._links[content_document_id] = [
                    l for l in self._links[content_document_id] if l["target_id"] != canon_target
                ]

    def delete_content_version(self, content_version_id: str) -> None:
        """Mark a ContentVersion deleted."""
        with self._lock:
            if content_version_id in self._files:
                self._files[content_version_id]["is_deleted"] = True

    # --- Delivery Registration (SF07DeliveryRegistrationV1) ---

    def register_delivery_set(
        self,
        receipt: DeliverySetReceipt,
        projection: ReviewProjection | None = None,
        caller_user_id: str | None = None,
    ) -> dict[str, ArtifactReviewRecord]:
        """Worker delivery registration (GEN-06 receipt -> JA_Artifact_Review__c records).

        Invariants:
        1. Both required formats (DOCX and PDF) must be present.
        2. Idempotent replay: exact same binding key with same hash/version preserves existing record,
           crucially preserving any human approval or supersession status!
        3. Conflicting byte/hash or remote IDs for the same binding key causes a rejection.
        4. Newly registered bindings start in 'draft' status.
        5. Worker caller cannot set approval fields or register review events.
        """
        with self._lock:
            # Caller privilege check: if caller provided, ensure worker or system
            if caller_user_id:
                role = self._user_roles.get(caller_user_id, "worker")
                # Candidate cannot invoke delivery registration
                if role == "candidate" and "Job_Automation_Worker" not in self._user_permissions.get(caller_user_id, set()):
                    raise PermissionError("Candidates cannot invoke worker delivery registration.")

            # Validate complete set of required formats
            required = set(receipt.required_formats)
            if not required or set(receipt.mappings.keys()) != required:
                raise ValueError(
                    f"Incomplete delivery set. Required formats {sorted(required)}, but mapped {sorted(receipt.mappings.keys())}."
                )

            if projection and projection.salesforce_request_id:
                salesforce_req_id = canonicalize_salesforce_id(projection.salesforce_request_id)
            elif receipt.mappings:
                first_map = next(iter(receipt.mappings.values()))
                salesforce_req_id = canonicalize_salesforce_id(first_map.target_record_id)
            else:
                salesforce_req_id = ""

            first_org = next(iter(receipt.mappings.values())).org_id if receipt.mappings else self.org_id
            warnings_text = ""
            if projection:
                joined_warns = "\n".join(f"- {w}" for w in projection.review_warnings)
                warnings_text = f"{projection.semantic_limits_notice}\n\nWarnings:\n{joined_warns}".strip()
            else:
                warnings_text = STATUTORY_NOTICE

            registered_records: dict[str, ArtifactReviewRecord] = {}

            for fmt in sorted(receipt.mappings.keys()):
                mapping: RemoteArtifactMapping = receipt.mappings[fmt]
                map_org = mapping.org_id or first_org
                binding_key = (
                    f"{map_org}:{salesforce_req_id}:{mapping.artifact_id}:{mapping.artifact_version}:{fmt}"
                )

                if binding_key in self._binding_keys:
                    existing_id = self._binding_keys[binding_key]
                    existing = self._review_records[existing_id]

                    # Check for conflicting bytes or remote IDs
                    if (
                        existing.content_hash != mapping.content_hash
                        or existing.content_version_id != mapping.content_version_id
                        or existing.content_document_id != mapping.content_document_id
                    ):
                        raise ValueError(
                            f"Delivery conflict for binding '{binding_key}': content hash or remote IDs do not match existing immutable record."
                        )

                    # Idempotent replay: return existing record without modifying approval status
                    registered_records[fmt] = existing
                    continue

                # Create new immutable review record
                review_id = f"a03{self._review_seq:012d}AAA"
                name = f"AR-{self._review_seq:06d}"
                self._review_seq += 1

                record = ArtifactReviewRecord(
                    review_id=review_id,
                    name=name,
                    binding_key=binding_key,
                    generation_request_id=salesforce_req_id,
                    org_id=map_org,
                    artifact_set_id=str(receipt.set_id),
                    artifact_id=str(mapping.artifact_id),
                    artifact_version=mapping.artifact_version,
                    format=fmt,
                    content_hash=mapping.content_hash,
                    size_bytes=1024,  # default
                    content_document_id=mapping.content_document_id,
                    content_version_id=mapping.content_version_id,
                    reconciliation_marker=mapping.marker,
                    delivery_receipt_ref=str(receipt.set_receipt_id),
                    delivered_at=receipt.created_at,
                    safe_warnings=warnings_text,
                    approval_status=ApprovalStatus.DRAFT,
                    review_revision=1,
                    contract_schema_version="1.0",
                )

                self._review_records[review_id] = record
                self._binding_keys[binding_key] = review_id
                registered_records[fmt] = record

                # Also register simulated Files gateway entries
                self.register_content_version(
                    content_version_id=mapping.content_version_id,
                    content_document_id=mapping.content_document_id,
                    title=f"Draft_{fmt.upper()}",
                )
                self.register_content_document_link(
                    content_document_id=mapping.content_document_id,
                    target_id=salesforce_req_id,
                    share_type="V",
                    visibility="AllUsers",
                )

            return registered_records

    # --- Candidate Access & File Visibility Verification ---

    def verify_candidate_file_access(
        self,
        content_version_id: str,
        target_record_id: str,
        candidate_user_id: str,
    ) -> FileAccessVerification:
        """Verify that a candidate has authorized access to the specific ContentVersion."""
        with self._lock:
            canon_target = canonicalize_salesforce_id(target_record_id)

            # Check if user has basic reviewer access
            role = self._user_roles.get(candidate_user_id, "candidate")
            if role == "unrelated":
                return FileAccessVerification(
                    is_accessible=False,
                    content_version_id=content_version_id,
                    content_document_id="",
                    share_type=None,
                    visibility=None,
                    error_reason="insufficient_user_privilege",
                )

            # Check file existence
            if content_version_id not in self._files:
                return FileAccessVerification(
                    is_accessible=False,
                    content_version_id=content_version_id,
                    content_document_id="",
                    share_type=None,
                    visibility=None,
                    error_reason="file_not_found",
                )

            file_info = self._files[content_version_id]
            if file_info.get("is_deleted", False):
                return FileAccessVerification(
                    is_accessible=False,
                    content_version_id=content_version_id,
                    content_document_id=file_info["document_id"],
                    share_type=None,
                    visibility=None,
                    error_reason="file_deleted",
                )

            doc_id = file_info["document_id"]
            links = self._links.get(doc_id, [])

            # Check for link to target record with acceptable ShareType and Visibility
            matching_links = [
                l for l in links if l["target_id"] == canon_target and l["share_type"] in ("V", "C", "I")
            ]

            if not matching_links:
                return FileAccessVerification(
                    is_accessible=False,
                    content_version_id=content_version_id,
                    content_document_id=doc_id,
                    share_type=None,
                    visibility=None,
                    error_reason="missing_record_link",
                )

            chosen_link = matching_links[0]
            # Visibility must allow candidate access (AllUsers or InternalUsers)
            if chosen_link["visibility"] not in ("AllUsers", "InternalUsers"):
                return FileAccessVerification(
                    is_accessible=False,
                    content_version_id=content_version_id,
                    content_document_id=doc_id,
                    share_type=chosen_link["share_type"],
                    visibility=chosen_link["visibility"],
                    error_reason="restricted_visibility",
                )

            return FileAccessVerification(
                is_accessible=True,
                content_version_id=content_version_id,
                content_document_id=doc_id,
                share_type=chosen_link["share_type"],
                visibility=chosen_link["visibility"],
                verified_at=datetime.now(timezone.utc),
            )

    # --- Review Command Execution (SF07ReviewCommandV1) ---

    def execute_review_command(self, command: ReviewCommand) -> ReviewCommandResult:
        """Execute a review command (approve, approve_and_replace, supersede) with full transactional guarantees.

        Invariants:
        1. Candidate must possess 'JA_Review_Generated_Documents' custom permission.
        2. Workers or unrelated principals cannot approve or supersede.
        3. Idempotent replay: resubmitting same token with identical payload returns 'replayed'.
           Resubmitting same token with conflicting payload returns 'conflict'.
        4. Parent Job row is locked first, then review rows, in stable ID order.
        5. Approval binds strictly to the exact (ContentVersionId, content_hash, revision).
        6. Explicit acknowledgment must be true.
        7. Enforces at most one current approved version per (Candidate, Job, DocumentType, Format).
        8. DOCX approval does NOT approve PDF. PDF remains draft.
        9. Delivery status must be Ready_for_Review; file must be candidate-accessible.
        10. Generation_Request__c status and Job__c candidate tracking fields are strictly untouched.
        """
        with self._lock:
            # 1. Authorize principal
            user_perms = self._user_permissions.get(command.candidate_user_id, set())
            role = self._user_roles.get(command.candidate_user_id, "candidate")
            if role == "worker":
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.REJECTED,
                    event_id=None,
                    current_status=None,
                    error_reason="worker_cannot_approve",
                    error_message="Worker processes are strictly prohibited from approving document drafts.",
                )
            if "JA_Review_Generated_Documents" not in user_perms:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.REJECTED,
                    event_id=None,
                    current_status=None,
                    error_reason="insufficient_privilege",
                    error_message="User lacks required JA_Review_Generated_Documents permission.",
                )

            # 2. Replay check
            canon_payload = command.to_canonical_payload()
            if command.event_key in self._event_keys:
                existing_event_id, existing_payload = self._event_keys[command.event_key]
                if existing_payload == canon_payload:
                    existing_event = self._events[existing_event_id]
                    target_rec = self._review_records.get(existing_event.artifact_review_id)
                    current_status = target_rec.approval_status if target_rec else None
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.REPLAYED,
                        event_id=existing_event_id,
                        current_status=current_status,
                        review_record=target_rec,
                        is_replayed=True,
                    )
                else:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.CONFLICT,
                        event_id=None,
                        current_status=None,
                        error_reason="idempotency_payload_conflict",
                        error_message="Submission token already exists with conflicting parameters.",
                    )

            # 3. Explicit acknowledgment check
            if not command.explicit_acknowledgment:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.REJECTED,
                    event_id=None,
                    current_status=None,
                    error_reason="missing_acknowledgment",
                    error_message="Candidate must explicitly acknowledge review before approving.",
                )

            # 4. Target record check
            if command.selected_review_id not in self._review_records:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.REJECTED,
                    event_id=None,
                    current_status=None,
                    error_reason="record_not_found",
                    error_message=f"Artifact review record '{command.selected_review_id}' does not exist.",
                )

            target = self._review_records[command.selected_review_id]
            req_id = target.generation_request_id
            req = self.submission_service.get_request(req_id)
            if not req:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.REJECTED,
                    event_id=None,
                    current_status=None,
                    error_reason="request_not_found",
                    error_message=f"Parent Generation Request '{req_id}' not found.",
                )

            # Must be Ready_for_Review
            if req.status != "Ready_for_Review":
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.REJECTED,
                    event_id=None,
                    current_status=target.approval_status,
                    error_reason="request_not_ready",
                    error_message=f"Request is in '{req.status}' state, not Ready_for_Review.",
                )

            # 5. Check exact version identity and revision match
            if target.content_version_id != command.expected_version_id:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.CONFLICT,
                    event_id=None,
                    current_status=target.approval_status,
                    error_reason="version_mismatch",
                    error_message=f"ContentVersion ID mismatch: expected '{command.expected_version_id}', got '{target.content_version_id}'.",
                )
            if target.content_hash != command.expected_content_hash:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.CONFLICT,
                    event_id=None,
                    current_status=target.approval_status,
                    error_reason="hash_mismatch",
                    error_message=f"Content hash mismatch: expected '{command.expected_content_hash}', got '{target.content_hash}'.",
                )
            if target.review_revision != command.expected_review_revision:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.CONFLICT,
                    event_id=None,
                    current_status=target.approval_status,
                    error_reason="stale_revision",
                    error_message=f"Stale review revision: expected {command.expected_review_revision}, currently {target.review_revision}.",
                )

            # 6. Verify file access at decision time
            access_res = self.verify_candidate_file_access(
                content_version_id=target.content_version_id,
                target_record_id=req_id,
                candidate_user_id=command.candidate_user_id,
            )
            if not access_res.is_accessible:
                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.REJECTED,
                    event_id=None,
                    current_status=target.approval_status,
                    error_reason=access_res.error_reason or "inaccessible_file",
                    error_message=f"Candidate cannot access file ({access_res.error_reason}). Approval blocked.",
                )

            # 7. Check existing approvals in the same scope (Job + DocumentType + Format)
            existing_approved = self._find_approved_record(
                job_id=req.job_id,
                document_type=req.document_type,
                format=target.format,
            )

            now = datetime.now(timezone.utc)

            # --- Action: APPROVE ---
            if command.action == ReviewAction.APPROVE:
                if target.approval_status != ApprovalStatus.DRAFT:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.CONFLICT,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="invalid_state_transition",
                        error_message=f"Cannot approve record in '{target.approval_status.value}' status.",
                    )
                if existing_approved:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.CONFLICT,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="approval_already_exists",
                        error_message=(
                            f"An approved {target.format.upper()} draft already exists ({existing_approved.name}). "
                            "Use 'approve_and_replace' to confirm superseding the existing approved draft."
                        ),
                    )

                event_id = f"a04{self._event_seq:012d}AAA"
                event_name = f"ARE-{self._event_seq:06d}"
                self._event_seq += 1

                event = ArtifactReviewEventRecord(
                    event_id=event_id,
                    name=event_name,
                    event_key=command.event_key,
                    artifact_review_id=target.review_id,
                    action=ReviewAction.APPROVE,
                    previous_status=target.approval_status.value,
                    new_status=ApprovalStatus.APPROVED.value,
                    prior_review_revision=target.review_revision,
                    new_review_revision=target.review_revision + 1,
                    actor=command.candidate_user_id,
                    event_timestamp=now,
                    selected_content_version_id=target.content_version_id,
                    selected_content_hash=target.content_hash,
                    candidate_notes=command.candidate_notes,
                )

                updated_target = ArtifactReviewRecord(
                    **{
                        **target.__dict__,
                        "approval_status": ApprovalStatus.APPROVED,
                        "approved_by": command.candidate_user_id,
                        "approved_at": now,
                        "approval_event_ref": event_id,
                        "review_revision": target.review_revision + 1,
                    }
                )

                self._events[event_id] = event
                self._event_keys[command.event_key] = (event_id, canon_payload)
                self._review_records[target.review_id] = updated_target

                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.RECORDED,
                    event_id=event_id,
                    current_status=ApprovalStatus.APPROVED,
                    review_record=updated_target,
                )

            # --- Action: APPROVE_AND_REPLACE ---
            elif command.action == ReviewAction.APPROVE_AND_REPLACE:
                if not command.replaced_review_id:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.REJECTED,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="missing_replacement_target",
                        error_message="Must specify replaced_review_id for approve_and_replace action.",
                    )
                if command.replaced_review_id not in self._review_records:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.REJECTED,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="replaced_record_not_found",
                        error_message=f"Replaced record '{command.replaced_review_id}' does not exist.",
                    )

                replaced = self._review_records[command.replaced_review_id]
                replaced_req = self.submission_service.get_request(replaced.generation_request_id)
                if not replaced_req or replaced_req.job_id != req.job_id or replaced_req.document_type != req.document_type:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.REJECTED,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="cross_job_or_type_replacement",
                        error_message="Cannot replace an artifact from a different Job or document type.",
                    )
                if replaced.format != target.format:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.REJECTED,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="format_mismatch",
                        error_message=f"Cannot replace {replaced.format.upper()} with {target.format.upper()}.",
                    )
                if replaced.approval_status != ApprovalStatus.APPROVED:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.CONFLICT,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="stale_replacement_target",
                        error_message=f"Target replaced record is '{replaced.approval_status.value}', not 'approved'.",
                    )

                # Atomic execution: supersede old, approve new
                event_id = f"a04{self._event_seq:012d}AAA"
                event_name = f"ARE-{self._event_seq:06d}"
                self._event_seq += 1

                event = ArtifactReviewEventRecord(
                    event_id=event_id,
                    name=event_name,
                    event_key=command.event_key,
                    artifact_review_id=target.review_id,
                    action=ReviewAction.APPROVE_AND_REPLACE,
                    previous_status=target.approval_status.value,
                    new_status=ApprovalStatus.APPROVED.value,
                    prior_review_revision=target.review_revision,
                    new_review_revision=target.review_revision + 1,
                    actor=command.candidate_user_id,
                    event_timestamp=now,
                    selected_content_version_id=target.content_version_id,
                    selected_content_hash=target.content_hash,
                    replaced_artifact_review_id=replaced.review_id,
                    candidate_notes=command.candidate_notes,
                )

                updated_replaced = ArtifactReviewRecord(
                    **{
                        **replaced.__dict__,
                        "approval_status": ApprovalStatus.SUPERSEDED,
                        "superseded_by": target.review_id,
                        "superseded_at": now,
                        "review_revision": replaced.review_revision + 1,
                    }
                )

                updated_target = ArtifactReviewRecord(
                    **{
                        **target.__dict__,
                        "approval_status": ApprovalStatus.APPROVED,
                        "approved_by": command.candidate_user_id,
                        "approved_at": now,
                        "approval_event_ref": event_id,
                        "review_revision": target.review_revision + 1,
                    }
                )

                self._events[event_id] = event
                self._event_keys[command.event_key] = (event_id, canon_payload)
                self._review_records[replaced.review_id] = updated_replaced
                self._review_records[target.review_id] = updated_target

                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.RECORDED,
                    event_id=event_id,
                    current_status=ApprovalStatus.APPROVED,
                    review_record=updated_target,
                )

            # --- Action: SUPERSEDE ---
            elif command.action == ReviewAction.SUPERSEDE:
                if target.approval_status == ApprovalStatus.SUPERSEDED:
                    return ReviewCommandResult(
                        outcome=ReviewCommandOutcome.CONFLICT,
                        event_id=None,
                        current_status=target.approval_status,
                        error_reason="already_superseded",
                        error_message="Record is already superseded.",
                    )

                event_id = f"a04{self._event_seq:012d}AAA"
                event_name = f"ARE-{self._event_seq:06d}"
                self._event_seq += 1

                event = ArtifactReviewEventRecord(
                    event_id=event_id,
                    name=event_name,
                    event_key=command.event_key,
                    artifact_review_id=target.review_id,
                    action=ReviewAction.SUPERSEDE,
                    previous_status=target.approval_status.value,
                    new_status=ApprovalStatus.SUPERSEDED.value,
                    prior_review_revision=target.review_revision,
                    new_review_revision=target.review_revision + 1,
                    actor=command.candidate_user_id,
                    event_timestamp=now,
                    selected_content_version_id=target.content_version_id,
                    selected_content_hash=target.content_hash,
                    candidate_notes=command.candidate_notes,
                )

                updated_target = ArtifactReviewRecord(
                    **{
                        **target.__dict__,
                        "approval_status": ApprovalStatus.SUPERSEDED,
                        "superseded_at": now,
                        "review_revision": target.review_revision + 1,
                    }
                )

                self._events[event_id] = event
                self._event_keys[command.event_key] = (event_id, canon_payload)
                self._review_records[target.review_id] = updated_target

                return ReviewCommandResult(
                    outcome=ReviewCommandOutcome.RECORDED,
                    event_id=event_id,
                    current_status=ApprovalStatus.SUPERSEDED,
                    review_record=updated_target,
                )

            return ReviewCommandResult(
                outcome=ReviewCommandOutcome.REJECTED,
                event_id=None,
                current_status=target.approval_status,
                error_reason="unsupported_action",
                error_message=f"Action '{command.action}' is not supported.",
            )

    # --- Scoped Review UI Projection ---

    def get_review_ui_state(self, request_id: str, candidate_user_id: str) -> ReviewUIState:
        """Construct truthful review UI projection matching SF-07 progress & approval rules."""
        with self._lock:
            canon_req_id = canonicalize_salesforce_id(request_id)
            req = self.submission_service.get_request(canon_req_id)
            if not req:
                raise ValueError(f"Generation Request '{canon_req_id}' not found.")

            job = self.submission_service.get_job(req.job_id)
            job_title = job.job_title if job else "Unknown Job"

            # Progress headlines and descriptions
            status_headlines = {
                "Pending": "Queued — waiting for the local worker",
                "Running": "Generating",
                "Upload_Pending": "Upload pending — draft is not yet ready for review",
                "Ready_for_Review": "Delivered — ready for review",
                "Failed": "Generation failed",
            }
            status_descriptions = {
                "Pending": "Request is securely queued in Salesforce. It will be picked up when the local worker runs on your Windows machine.",
                "Running": "The local worker has claimed this request and is generating your draft document.",
                "Upload_Pending": "The local worker generated the draft, but delivery to Salesforce Files is pending or incomplete.",
                "Ready_for_Review": "Both DOCX and PDF drafts have been delivered and verified accessible. Review the drafts and approve when satisfied.",
                "Failed": f"Generation stopped: {req.error_message or req.error_reason or 'Unknown error'}",
            }

            status_headline = status_headlines.get(req.status, f"Status: {req.status}")
            status_desc = status_descriptions.get(req.status, "")

            # Offline worker feedback notice
            offline_notice = None
            if req.status == "Pending":
                offline_notice = (
                    "The local worker is currently offline or waiting for its scheduled polling interval. "
                    "No local processes are invoked synchronously from Salesforce."
                )

            # Find review records for this request
            req_reviews = [
                r for r in self._review_records.values() if r.generation_request_id == canon_req_id
            ]

            cards: dict[str, FormatReviewCard] = {}
            for fmt in ("docx", "pdf"):
                match = [r for r in req_reviews if r.format == fmt]
                if match:
                    rec = match[0]
                    # Verify candidate access
                    access = self.verify_candidate_file_access(
                        rec.content_version_id, canon_req_id, candidate_user_id
                    )

                    # Timestamp formatted in Berlin
                    del_berlin = rec.delivered_at.astimezone(BERLIN_TZ).strftime("%Y-%m-%d %H:%M:%S %Z")
                    app_berlin = (
                        rec.approved_at.astimezone(BERLIN_TZ).strftime("%Y-%m-%d %H:%M:%S %Z")
                        if rec.approved_at
                        else None
                    )

                    # Check if an existing approval exists for another version in this job/doc_type
                    existing_approved = self._find_approved_record(req.job_id, req.document_type, fmt)
                    is_this_approved = rec.approval_status == ApprovalStatus.APPROVED

                    can_app = (
                        req.status == "Ready_for_Review"
                        and access.is_accessible
                        and rec.approval_status == ApprovalStatus.DRAFT
                        and (existing_approved is None)
                    )
                    can_replace = (
                        req.status == "Ready_for_Review"
                        and access.is_accessible
                        and rec.approval_status == ApprovalStatus.DRAFT
                        and (existing_approved is not None and existing_approved.review_id != rec.review_id)
                    )
                    can_sup = (
                        access.is_accessible
                        and rec.approval_status in (ApprovalStatus.DRAFT, ApprovalStatus.APPROVED)
                    )

                    del_status = "delivered" if access.is_accessible else "unavailable"
                    access_msg = None if access.is_accessible else f"File unavailable: {access.error_reason}"

                    download_url = (
                        f"/sfc/servlet.shepherd/version/download/{rec.content_version_id}"
                        if access.is_accessible
                        else None
                    )

                    cards[fmt] = FormatReviewCard(
                        format=fmt,
                        review_id=rec.review_id,
                        content_version_id=rec.content_version_id,
                        content_document_id=rec.content_document_id,
                        content_hash=rec.content_hash,
                        size_bytes=rec.size_bytes,
                        delivery_status=del_status,
                        approval_status=rec.approval_status.value,
                        delivered_at_berlin=del_berlin,
                        approved_at_berlin=app_berlin,
                        approved_by=rec.approved_by,
                        is_accessible=access.is_accessible,
                        download_url=download_url,
                        can_approve=can_app,
                        can_approve_and_replace=can_replace,
                        can_supersede=can_sup,
                        access_message=access_msg,
                    )
                else:
                    cards[fmt] = FormatReviewCard(
                        format=fmt,
                        review_id=None,
                        content_version_id=None,
                        content_document_id=None,
                        content_hash=None,
                        size_bytes=None,
                        delivery_status="upload_pending",
                        approval_status="draft",
                        delivered_at_berlin=None,
                        approved_at_berlin=None,
                        approved_by=None,
                        is_accessible=False,
                        download_url=None,
                        can_approve=False,
                        can_approve_and_replace=False,
                        can_supersede=False,
                        access_message="File upload is still pending.",
                    )

            # Find all currently approved records for this job/doc_type
            currently_approved: dict[str, str] = {}
            for fmt in ("docx", "pdf"):
                app_rec = self._find_approved_record(req.job_id, req.document_type, fmt)
                if app_rec:
                    currently_approved[fmt] = app_rec.review_id

            all_delivered = all(c.delivery_status == "delivered" for c in cards.values())

            # Warnings
            warnings_list: list[str] = []
            if req_reviews and req_reviews[0].safe_warnings:
                lines = req_reviews[0].safe_warnings.split("\n")
                warnings_list = [l.strip("- ") for l in lines if l.startswith("- ")]

            return ReviewUIState(
                request_id=canon_req_id,
                request_name=req.name,
                job_id=req.job_id,
                job_title=job_title,
                document_type=req.document_type,
                language=req.language,
                template_id=req.template_id,
                request_status=req.status,
                status_headline=status_headline,
                status_description=status_desc,
                offline_worker_notice=offline_notice,
                statutory_warning=STATUTORY_NOTICE,
                warnings=warnings_list,
                frozen_versions={
                    "posting_revision": getattr(req, "frozen_posting_revision", None) or "Unclaimed",
                    "profile_version": getattr(req, "frozen_profile_version", None) or "Unclaimed",
                    "policy_version": getattr(req, "frozen_policy_version", None) or "Unclaimed",
                    "template_version": getattr(req, "frozen_template_version", None) or "Unclaimed",
                },
                cards=cards,
                currently_approved_format_ids=currently_approved,
                all_formats_delivered=all_delivered,
                can_regenerate=True,
                error_message=req.error_message,
                error_reason=req.error_reason,
            )

    # --- Regeneration via SF-06 ---

    def request_regeneration(
        self,
        predecessor_request_id: str,
        submission_token: str,
        candidate_user_id: str,
        template_id: str | None = None,
        language: str | None = None,
        context_strategy: str | None = None,
        allow_unavailable_job: bool = False,
    ) -> SubmissionResult:
        """Trigger draft regeneration through SF-06 submission service.

        Invariants:
        1. Passes predecessor_request_id to preserve audit lineage.
        2. allow_unavailable_job defaults strictly to False (resets prior consent).
        3. Prior approved version on predecessor is NOT copied or modified.
        4. Replay of same token returns the replayed successor request.
        """
        with self._lock:
            canon_pred_id = canonicalize_salesforce_id(predecessor_request_id)
            pred = self.submission_service.get_request(canon_pred_id)
            if not pred:
                raise ValueError(f"Predecessor request '{canon_pred_id}' not found.")

            intent = SubmissionIntent(
                job_id=pred.job_id,
                document_type=pred.document_type,
                template_id=template_id or pred.template_id,
                language=language or pred.language,
                context_strategy=context_strategy or pred.context_strategy,
                allow_unavailable_job=allow_unavailable_job,
                creation_mode="regenerate",
                predecessor_request_id=canon_pred_id,
                submission_token=submission_token,
                user_id=candidate_user_id,
            )

            # Delegate to SF-06 submission service
            return self.submission_service.submit(intent)

    # --- Internal Queries ---

    def _find_approved_record(
        self,
        job_id: str,
        document_type: str,
        format: str,
    ) -> ArtifactReviewRecord | None:
        """Find the currently approved review record for (job, document_type, format)."""
        canon_job_id = canonicalize_salesforce_id(job_id)
        for rec in self._review_records.values():
            if rec.format != format or rec.approval_status != ApprovalStatus.APPROVED:
                continue
            req = self.submission_service.get_request(rec.generation_request_id)
            if req and req.job_id == canon_job_id and req.document_type == document_type:
                return rec
        return None

    def get_review_record(self, review_id: str) -> ArtifactReviewRecord | None:
        with self._lock:
            return self._review_records.get(review_id)

    def get_event(self, event_id: str) -> ArtifactReviewEventRecord | None:
        with self._lock:
            return self._events.get(event_id)

    def list_events_for_review(self, review_id: str) -> list[ArtifactReviewEventRecord]:
        with self._lock:
            return [
                e
                for e in self._events.values()
                if e.artifact_review_id == review_id
                or e.replaced_artifact_review_id == review_id
            ]
