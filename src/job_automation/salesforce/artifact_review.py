@dataclass(frozen=True)
class ReviewCommand:
    """Command payload representing candidate intent to approve, replace, or supersede."""

    action: ReviewAction
    selected_review_id: str
    expected_version_id: str
    expected_content_hash: str
    expected_review_revision: int
    intent_token: str
    candidate_user_id: str
    replaced_review_id: str | None = None
    candidate_notes: str | None = None
    explicit_acknowledgment: bool = False

    def __init__(
        self,
        action: ReviewAction,
        selected_review_id: str,
        expected_version_id: str,
        expected_content_hash: str,
        expected_review_revision: int,
        intent_token: str,
        candidate_user_id: str,
        replaced_review_id: str | None = None,
        candidate_notes: str | None = None,
        candidateNotes: str | None = None,
        explicit_acknowledgment: bool = False,
    ) -> None:
        object.__setattr__(self, "action", action)
        object.__setattr__(self, "selected_review_id", selected_review_id)
        object.__setattr__(self, "expected_version_id", expected_version_id)
        object.__setattr__(self, "expected_content_hash", expected_content_hash)
        object.__setattr__(self, "expected_review_revision", expected_review_revision)
        object.__setattr__(self, "intent_token", intent_token)
        object.__setattr__(self, "candidate_user_id", candidate_user_id)
        object.__setattr__(self, "replaced_review_id", replaced_review_id)
        notes = candidate_notes if candidate_notes is not None else candidateNotes
        object.__setattr__(self, "candidate_notes", notes)
        object.__setattr__(self, "explicit_acknowledgment", explicit_acknowledgment)

    @property
    def event_key(self) -> str:
        return f"{self.candidate_user_id}:{self.intent_token.strip()}"

    def to_canonical_payload(self) -> str:
        data = {
            "action": self.action.value,
            "candidateNotes": (self.candidate_notes or "").strip(),
            "expectedContentHash": self.expected_content_hash.strip(),
            "expectedReviewRevision": self.expected_review_revision,
            "expectedVersionId": self.expected_version_id.strip(),
            "explicitAcknowledgment": bool(self.explicit_acknowledgment),
            "replacedReviewId": self.replaced_review_id or "",
            "selectedReviewId": self.selected_review_id.strip(),
        }
        return json.dumps(data, sort_keys=True, separators=(",", ":"))


