"""Remote Salesforce recovery export assembler and completeness validator (OPS-01-S05 / SF-04-S05).

Enforces:
- Verification of export packages generated by CandidateExportService (SF-04).
- Reading validated export manifest, file hashes, and true capture intervals.
- Fallback inspection of durable candidate_snapshots when export package directory is not supplied.
- Strict detection of incomplete scans, missing candidate fields, or absent SF-04 handoff.
- Truthful reporting of object coverage (Job__c vs Company__c).
- Preservation of null versus absent values and version tokens.
"""

from __future__ import annotations

import hashlib
import json
import logging
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from job_automation.operations.records import (
    RemoteCompleteness,
    RemoteRecoveryExport,
)
from job_automation.salesforce.export_verification import verify_export_package
from job_automation.salesforce.portability_records import ExportManifest
from job_automation.salesforce.sync_settings import SyncMappingConfig
from job_automation.storage.engine import StorageEngine

logger = logging.getLogger(__name__)


def assemble_remote_export(
    engine: StorageEngine,
    config: SyncMappingConfig | None = None,
    scan_id: str | None = None,
    export_dir: Path | str | None = None,
    max_freshness_hours: float = 24.0,
) -> RemoteRecoveryExport:
    """Extract candidate-owned snapshots and evaluate remote export completeness."""
    now_dt = datetime.now(timezone.utc)
    s_id = scan_id or f"scan-{now_dt.strftime('%Y%m%d%H%M%S')}-{uuid.uuid4().hex[:8]}"

    if config is None:
        return RemoteRecoveryExport(
            scan_id=s_id,
            start_time=now_dt,
            end_time=now_dt,
            org_id="unknown",
            object_coverage=[],
            expected_count=0,
            read_count=0,
            saved_count=0,
            skipped_count=0,
            missing_fields=[],
            per_record_tokens={},
            completeness_status=RemoteCompleteness.LOCAL_ONLY_ABSENT_SF04,
            checksum="",
            notes="SF-04 handoff and sync mapping config absent. Local-only recovery available.",
        )

    # 1. If an explicit export directory is supplied, verify and load from manifest
    if export_dir is not None:
        p_dir = Path(export_dir).resolve()
        manifest_file = p_dir / "manifest.json"
        if manifest_file.is_file():
            try:
                manifest_data = json.loads(manifest_file.read_text(encoding="utf-8"))
                manifest = ExportManifest.model_validate(manifest_data)

                # Verify package bytes and relationship closure
                verify_report = verify_export_package(
                    p_dir,
                    expected_org_id=config.expected_org_id,
                    expected_mapping_version=config.mapping_version,
                )

                # Check freshness
                age_hours = (now_dt - manifest.end_time).total_seconds() / 3600.0
                is_stale = age_hours > max_freshness_hours

                if not verify_report.is_valid:
                    completeness = RemoteCompleteness.INCOMPLETE
                    notes = f"Export package verification failed: {'; '.join(verify_report.issues)}"
                elif is_stale:
                    completeness = RemoteCompleteness.PARTIAL
                    notes = f"Export package is stale ({age_hours:.1f} hours old, max allowed {max_freshness_hours}h)."
                elif manifest.completeness_status == "complete":
                    completeness = RemoteCompleteness.COMPLETE
                    notes = f"Verified complete SF-04 export package: {manifest.notes}"
                else:
                    completeness = RemoteCompleteness.PARTIAL
                    notes = f"SF-04 export package is partial: {manifest.notes}"

                # Calculate package checksum from manifest files
                checksum_parts = [f"{f.relative_path}:{f.sha256}" for f in manifest.files]
                pkg_checksum = hashlib.sha256(";".join(sorted(checksum_parts)).encode("utf-8")).hexdigest()

                object_cov = [config.job_object]
                if manifest.saved_counts.get("companies", 0) > 0 or (p_dir / "companies.jsonl").is_file():
                    object_cov.append(config.company_object)

                return RemoteRecoveryExport(
                    scan_id=manifest.scan_id,
                    start_time=manifest.start_time,
                    end_time=manifest.end_time,
                    org_id=manifest.org_id,
                    object_coverage=object_cov,
                    expected_count=manifest.expected_counts.get("jobs") or manifest.saved_counts.get("jobs", 0),
                    read_count=manifest.read_counts.get("jobs", 0),
                    saved_count=manifest.saved_counts.get("jobs", 0),
                    skipped_count=manifest.skipped_counts.get("jobs", 0),
                    missing_fields=manifest.missing_fields,
                    per_record_tokens=manifest.source_tokens,
                    completeness_status=completeness,
                    checksum=pkg_checksum,
                    notes=notes,
                )
            except Exception as exc:
                logger.warning("Failed to load export package from '%s': %s", p_dir, exc)

    # 2. Fallback: inspect candidate snapshots in durable storage
    conn = engine.conn
    cursor = conn.execute(
        """
        SELECT snapshot_id, org_id, canonical_job_id, remote_record_id,
               mapping_version, snapshot_hash, candidate_fields_json,
               source_modification_token, observed_at, created_at
        FROM candidate_snapshots
        WHERE org_id = ?
        ORDER BY canonical_job_id, observed_at ASC
        """,
        (config.expected_org_id,),
    )
    rows = cursor.fetchall()

    # Check total tracked canonical jobs to verify completeness
    job_cursor = conn.execute("SELECT COUNT(*) as cnt FROM canonical_jobs")
    total_tracked_jobs = int(job_cursor.fetchone()["cnt"])

    # Check latest backup checkpoint
    latest_cp = engine.candidate_snapshots.get_latest_checkpoint(config.expected_org_id)
    is_checkpoint_complete = bool(latest_cp and latest_cp.get("is_complete"))

    # Resolve real capture times from checkpoint if available
    start_time = now_dt
    end_time = now_dt
    if latest_cp and latest_cp.get("started_at"):
        try:
            start_time = datetime.fromisoformat(latest_cp["started_at"])
            if latest_cp.get("completed_at"):
                end_time = datetime.fromisoformat(latest_cp["completed_at"])
        except ValueError:
            pass

    per_record_tokens: dict[str, str] = {}
    missing_fields: list[str] = []
    seen_jobs: set[str] = set()
    checksum_parts_db: list[str] = []

    for row in rows:
        job_id_str = row["canonical_job_id"]
        seen_jobs.add(job_id_str)
        mod_token = row["source_modification_token"] or ""
        per_record_tokens[job_id_str] = mod_token

        fields = json.loads(row["candidate_fields_json"])
        for req_field in config.candidate_fields:
            if req_field not in fields and req_field not in missing_fields:
                missing_fields.append(req_field)

        checksum_parts_db.append(f"{job_id_str}:{row['snapshot_hash']}:{mod_token}")

    checksum = hashlib.sha256(";".join(sorted(checksum_parts_db)).encode("utf-8")).hexdigest()

    saved_count = len(seen_jobs)
    skipped_count = max(0, total_tracked_jobs - saved_count)

    # Determine completeness
    if not config.candidate_fields:
        completeness = RemoteCompleteness.LOCAL_ONLY_ABSENT_SF04
        notes = "No candidate fields configured in sync mapping."
    elif total_tracked_jobs > 0 and saved_count == 0:
        completeness = RemoteCompleteness.INCOMPLETE
        notes = "No candidate snapshots found for tracked jobs; scan has not run."
    elif missing_fields:
        completeness = RemoteCompleteness.PARTIAL
        notes = f"Missing candidate fields in snapshots: {', '.join(missing_fields)}"
    elif total_tracked_jobs > saved_count or not is_checkpoint_complete:
        completeness = RemoteCompleteness.PARTIAL
        notes = f"Partial coverage: {saved_count}/{total_tracked_jobs} tracked jobs captured. Checkpoint complete={is_checkpoint_complete}."
    else:
        completeness = RemoteCompleteness.COMPLETE
        notes = f"Complete candidate export: all {saved_count} tracked jobs captured."

    return RemoteRecoveryExport(
        scan_id=s_id,
        start_time=start_time,
        end_time=end_time,
        org_id=config.expected_org_id,
        object_coverage=[config.job_object, config.company_object],
        expected_count=total_tracked_jobs,
        read_count=len(rows),
        saved_count=saved_count,
        skipped_count=skipped_count,
        missing_fields=missing_fields,
        per_record_tokens=per_record_tokens,
        completeness_status=completeness,
        checksum=checksum,
        notes=notes,
    )
