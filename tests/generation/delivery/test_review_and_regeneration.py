def test_review_projection_preserves_warnings_and_semantic_limits() -> None:
    req_id = uuid.uuid4()
    now = datetime.now(timezone.utc)
    req = GenerationRequest(
        request_id=req_id,
        salesforce_request_id="a01000000000001AAA",
        canonical_job_id=uuid.uuid4(),
        document_type=DocumentType.CV,
        template_id="content-basic",
        created_at=now,
    )

    art_id = uuid.uuid4()
    marker = build_reconciliation_marker(req_id, art_id, 1)
    mapping = RemoteArtifactMapping(
        mapping_id=uuid.uuid4(),
        intent_id=uuid.uuid4(),
        request_id=req_id,
        artifact_id=art_id,
        artifact_version=1,
        artifact_format="docx",
        content_hash="sha256:" + "a" * 64,
        org_id="00D000000000001EAA",
        content_document_id="069000000000001AAA",
        content_version_id="068000000000001AAA",
        marker=marker,
        target_record_id="a01000000000001AAA",
        link_id="06A000000000001AAA",
        acknowledged_at=now,
    )
    access_rcpt = AccessibilityReceipt(
        receipt_id=uuid.uuid4(),
        mapping_id=mapping.mapping_id,
        request_id=req_id,
        artifact_id=mapping.artifact_id,
        artifact_version=1,
        artifact_format="docx",
        content_version_id=mapping.content_version_id,
        content_document_id=mapping.content_document_id,
        target_record_id=mapping.target_record_id,
        verification_method="sharing_policy_check",
        verified_at=now,
    )
    delivery_set = DeliverySetReceipt(
        set_receipt_id=uuid.uuid4(),
        request_id=req_id,
        set_id=uuid.uuid4(),
        set_version=1,
        required_formats=["docx"],
        mappings={"docx": mapping},
        accessibility_receipts={"docx": access_rcpt},
        review_route="https://test.salesforce.com/view",
        created_at=now,
    )

    warnings = [
        "Subjective phrase in summary requires human review",
        "Metric '+35%' entails unverified assumption",
    ]
    proj = build_review_projection(req, delivery_set, warnings=warnings)

    assert proj.review_warnings == warnings
    assert "Draft generated by automated pipeline" in proj.semantic_limits_notice
    assert proj.result_version_refs["docx"] == "068000000000001AAA"

    # Format payload
    payload = format_review_payload(proj)
    assert payload["Status__c"] == "Ready_for_Review"
    assert payload["Remote_File_Id__c"] == "068000000000001AAA"
    assert "Warnings for reviewer:" in payload["Review_Notes__c"]
    assert "Metric '+35%'" in payload["Review_Notes__c"]


def test_regeneration_lineage_and_approval_isolation(storage: StorageEngine) -> None:
    job_id = uuid.uuid4()
    now = datetime.now(timezone.utc).isoformat()
    storage.conn.execute(
        "INSERT INTO canonical_jobs (canonical_job_id, company_name, availability, current_revision_id, first_seen_at, last_seen_at, job_json, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (str(job_id), "Test AG", "active", "rev1", now, now, "{}", now, now),
    )

    # Request A: initial request
    req_a_id = uuid.uuid4()
    req_a = GenerationRequest(
        request_id=req_a_id,
        salesforce_request_id="a01000000000001AAA",
        canonical_job_id=job_id,
        document_type=DocumentType.CV,
        template_id="content-basic",
        state=GenerationProcessing.READY_FOR_REVIEW,
        created_at=datetime.now(timezone.utc),
        claimed_at=datetime.now(timezone.utc),
        frozen_input_versions=FrozenInputVersions(
            posting_revision="rev1",
            profile_version="v1",
            policy_version="v1",
            template_version="v1",
        ),
    )
    storage.generation_requests.create_request(req_a)

    # Artifact for Request A is approved by user
    art_a = Artifact(
        artifact_id=uuid.uuid4(),
        request_id=req_a_id,
        artifact_version=1,
        format="docx",
        local_path="C:/artifacts/a.docx",
        content_hash="sha256:" + "1" * 64,
        size_bytes=1000,
        delivery_status="delivered",
        approval_status=DocumentApproval.APPROVED,
        created_at=datetime.now(timezone.utc),
    )
    storage.artifacts.save_artifact(art_a)

    # Request B: deliberate regeneration of Request A
    req_b_id = uuid.uuid4()
    req_b = GenerationRequest(
        request_id=req_b_id,
        salesforce_request_id="a01000000000002AAA",
        canonical_job_id=job_id,
        document_type=DocumentType.CV,
        template_id="content-basic",
        predecessor_request_id=req_a_id,
        created_at=datetime.now(timezone.utc),
    )
    storage.generation_requests.create_request(req_b)

    # Lineage validation passes
    valid, err = validate_regeneration_lineage(req_b, storage.generation_requests)
    assert valid is True
    assert err is None

    # Delivered artifact for Request B strictly starts in DRAFT!
    art_b = Artifact(
        artifact_id=uuid.uuid4(),
        request_id=req_b_id,
        artifact_version=1,
        format="docx",
        local_path="C:/artifacts/b.docx",
        content_hash="sha256:" + "2" * 64,
        size_bytes=1000,
        delivery_status="delivered",
        approval_status=DocumentApproval.DRAFT,
        created_at=datetime.now(timezone.utc),
    )
    ensure_draft_approval_status([art_b])

    # Assert Request A artifact remains APPROVED and was NOT modified
    saved_art_a = storage.artifacts.get_artifact(art_a.artifact_id)
    assert saved_art_a is not None
    assert saved_art_a.approval_status == DocumentApproval.APPROVED

    # If artifact has status other than draft, ensure_draft_approval_status raises
    with pytest.raises(ValueError, match="Delivered artifacts must strictly remain 'draft'"):
        ensure_draft_approval_status([art_a])
